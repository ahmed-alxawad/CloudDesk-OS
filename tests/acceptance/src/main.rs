async fn scan_host_key(host: &str, port: u16) -> Result<String> {
    let output = tokio::process::Command::new("ssh-keyscan")
        .args(["-t", "ed25519", "-p", &port.to_string(), host])
        .output()
        .await
        .context("failed to run ssh-keyscan")?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let key_field = stdout
        .lines()
        .find(|line| !line.starts_with('#'))
        .and_then(|line| line.split_whitespace().nth(2))
        .context("ssh-keyscan produced no usable host key line")?;
    Ok(key_field.to_string())
}

fn base64_of(bytes: [u8; 32]) -> String {
    use base64::Engine;
    base64::engine::general_purpose::STANDARD.encode(bytes)
}
